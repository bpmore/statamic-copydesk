<?php

declare(strict_types=1);

/*
 * Writes docs/pack-review.md: every entry in every bundled pack, in one
 * list, for a person to sign off that none of it copies a commercial
 * stylebook's wording (spec, acceptance 9). A test fails when a pack
 * changes and this has not been run again: `composer pack-review`.
 */

require __DIR__.'/../vendor/autoload.php';

use Bpmore\Copydesk\Style\Pack;
use Symfony\Component\Yaml\Yaml;

function packReview(string $packs): string
{
    $out = "# Bundled pack review\n\n";
    $out .= "Every entry Copydesk ships, for a person to check that none of it copies a\n";
    $out .= "commercial stylebook's entries, examples or wording (spec, acceptance 9).\n";
    $out .= "Generated by `composer pack-review`; do not edit by hand.\n\n";
    $out .= "Reviewed by: ______________________  Date: ____________\n";

    $files = glob(rtrim($packs, '/').'/*.yaml') ?: [];
    sort($files);

    foreach ($files as $file) {
        $name = basename($file, '.yaml');
        $pack = Pack::fromArray($name, Yaml::parseFile($file), $name);

        $out .= "\n## {$name}\n\n";
        $out .= trim((string) $pack->description)."\n";

        foreach ($pack->rules as $rule) {
            $out .= "\n### `{$rule->id}` ({$rule->type->value}, {$rule->severity->value})\n\n";
            $out .= "Message: {$rule->message}\n";

            foreach ($rule->options['words'] ?? [] as $word) {
                $instead = $word['replacements'] === [] ? 'say it another way' : implode(' / ', $word['replacements']);
                $out .= "\n- [ ] {$word['phrase']} -> {$instead}".($word['reason'] === null ? '' : ". {$word['reason']}");
            }

            if (isset($rule->options['pattern'])) {
                $out .= "\n- [ ] Pattern: `{$rule->options['pattern']}`";
            }

            if (isset($rule->options['checks'])) {
                $out .= "\n- [ ] Checks: ".implode(', ', $rule->options['checks']);
            }

            if (isset($rule->options['check'])) {
                $out .= "\n- [ ] Check: {$rule->options['check']}";
            }

            $out .= "\n";
        }
    }

    return $out;
}

if (realpath($_SERVER['SCRIPT_FILENAME'] ?? '') === realpath(__FILE__)) {
    file_put_contents(__DIR__.'/../docs/pack-review.md', packReview(__DIR__.'/../resources/packs'));
    echo "Wrote docs/pack-review.md\n";
}
